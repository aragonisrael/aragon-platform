) FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.create_unicorn_challenge_submission(
  TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, JSONB, JSONB, INTEGER, BOOLEAN, TEXT
) TO anon, authenticated, service_role;

-- ---------- הרשאות דשבורד (role = unicorn) ----------
CREATE OR REPLACE FUNCTION public.is_unicorn_reviewer()
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  uid uuid;
  ok boolean;
BEGIN
  uid := auth.uid();
  IF uid IS NULL THEN
    RETURN false;
  END IF;

  SELECT EXISTS (
    SELECT 1
    FROM public.users
    WHERE auth_user_id = uid
      AND role = 'unicorn'
      AND COALESCE(is_active, true) = true
  ) INTO ok;

  RETURN COALESCE(ok, false);
END;
$$;

ALTER FUNCTION public.is_unicorn_reviewer() OWNER TO postgres;
REVOKE ALL ON FUNCTION public.is_unicorn_reviewer() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_unicorn_reviewer() TO anon, authenticated, service_role;

ALTER TABLE public.unicorn_challenge_submissions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "unicorn_challenge_select_reviewer"
  ON public.unicorn_challenge_submissions;
CREATE POLICY "unicorn_challenge_select_reviewer"
  ON public.unicorn_challenge_submissions
  FOR SELECT TO authenticated
  USING (public.is_unicorn_reviewer() = true);

DROP POLICY IF EXISTS "unicorn_challenge_update_reviewer"
  ON public.unicorn_challenge_submissions;
CREATE POLICY "unicorn_challenge_update_reviewer"
  ON public.unicorn_challenge_submissions
  FOR UPDATE TO authenticated
  USING (public.is_unicorn_reviewer() = true)
