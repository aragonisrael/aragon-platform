-- ---------- טבלה ----------
CREATE TABLE IF NOT EXISTS public.unicorn_challenge_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_full_name TEXT NOT NULL,
  school_name TEXT NOT NULL,
  grade TEXT NOT NULL,
  parent_name TEXT NOT NULL,
  parent_phone TEXT NOT NULL,
  city TEXT NOT NULL,
  answers JSONB NOT NULL DEFAULT '{}'::jsonb,
  score_breakdown JSONB NOT NULL DEFAULT '{}'::jsonb,
  part12_percent INTEGER NOT NULL DEFAULT 0,
  passed BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT 'failed',
  notes TEXT,
  reviewed_by TEXT,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now()),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT unicorn_challenge_status_check
    CHECK (status IN ('passed', 'failed', 'pending_committee'))
);

CREATE INDEX IF NOT EXISTS idx_unicorn_challenge_created_at
  ON public.unicorn_challenge_submissions (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_unicorn_challenge_status
  ON public.unicorn_challenge_submissions (status);
CREATE INDEX IF NOT EXISTS idx_unicorn_challenge_parent_phone
  ON public.unicorn_challenge_submissions (parent_phone);

CREATE OR REPLACE FUNCTION public.touch_unicorn_challenge_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := timezone('utc', now());
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_unicorn_challenge_touch ON public.unicorn_challenge_submissions;
CREATE TRIGGER trg_unicorn_challenge_touch
  BEFORE UPDATE ON public.unicorn_challenge_submissions
  FOR EACH ROW
  EXECUTE FUNCTION public.touch_unicorn_challenge_updated_at();

-- ---------- RPC לאתר (שמירת הגשה) ----------
CREATE OR REPLACE FUNCTION public.create_unicorn_challenge_submission(
  p_student_full_name TEXT,
  p_school_name TEXT,
  p_grade TEXT,
  p_parent_name TEXT,
  p_parent_phone TEXT,
  p_city TEXT,
  p_answers JSONB,
  p_score_breakdown JSONB,
  p_part12_percent INTEGER,
  p_passed BOOLEAN,
  p_status TEXT
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  new_id BIGINT;
  clean_student TEXT := trim(COALESCE(p_student_full_name, ''));
  clean_school TEXT := trim(COALESCE(p_school_name, ''));
  clean_grade TEXT := trim(COALESCE(p_grade, ''));
  clean_parent TEXT := trim(COALESCE(p_parent_name, ''));
  clean_phone TEXT := trim(COALESCE(p_parent_phone, ''));
  clean_city TEXT := trim(COALESCE(p_city, ''));
  clean_status TEXT := trim(COALESCE(p_status, ''));
BEGIN
  IF clean_student = '' OR clean_school = '' OR clean_grade = ''
     OR clean_parent = '' OR clean_phone = '' OR clean_city = '' THEN
    RAISE EXCEPTION 'missing required fields';
  END IF;

  IF clean_status NOT IN ('passed', 'failed', 'pending_committee') THEN
    RAISE EXCEPTION 'invalid status';
  END IF;

  INSERT INTO public.unicorn_challenge_submissions (
    student_full_name,
    school_name,
    grade,
    parent_name,
    parent_phone,
    city,
    answers,
    score_breakdown,
    part12_percent,
    passed,
    status
  ) VALUES (
    clean_student,
    clean_school,
    clean_grade,
    clean_parent,
    clean_phone,
    clean_city,
    COALESCE(p_answers, '{}'::jsonb),
    COALESCE(p_score_breakdown, '{}'::jsonb),
    COALESCE(p_part12_percent, 0),
    COALESCE(p_passed, false),
    clean_status
  )
  RETURNING id INTO new_id;

  RETURN new_id;
END;
$$;

ALTER FUNCTION public.create_unicorn_challenge_submission(
  TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, JSONB, JSONB, INTEGER, BOOLEAN, TEXT
) OWNER TO postgres;

REVOKE ALL ON FUNCTION public.create_unicorn_challenge_submission(
